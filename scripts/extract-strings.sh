#!/usr/bin/env bash
# Regenerates the English base string table, Resources/en.lproj/Localizable.strings, from the sources.
# Keys are the English text (see Sources/ArborCore/Accessibility/L10n.swift). Collected:
#   L10n.tr("…"), L10n.format("…", …)          strings routed explicitly
#   title: "…", tooltip: "…" in ExplorerCommand  command titles and tooltips (routed by ExplorerCommand)
#   ChromeButton(… tooltip: "…")                 button tooltips (routed by ChromeButton)
# Strings built with interpolation ("\(…)") are skipped: route them with L10n.format and a %@ key.
# Usage: scripts/extract-strings.sh [--check]   (--check fails if the table is out of date)
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=Resources/en.lproj/Localizable.strings
TMP=$(mktemp)
trap 'rm -f "$TMP" "$TMP.sorted"' EXIT
find Sources -name '*.swift' -print0 | xargs -0 perl -ne '
    while (/L10n\.(?:tr|format)\(\s*"((?:[^"\\]|\\.)*)"/g) { print "$1\n" }
    while (/\b(?:title|tooltip):\s*"((?:[^"\\]|\\.)*)"/g) { print "$1\n" }
' | grep -v '\\(' | grep -v '^$' > "$TMP"
LC_ALL=C sort -u "$TMP" > "$TMP.sorted"
{
  echo "/* English base strings for Arbor. Generated by scripts/extract-strings.sh; keys are the English text. */"
  echo "/* Translations go in <language>.lproj/Localizable.strings with the same keys. */"
  echo
  while IFS= read -r line; do
    printf '"%s" = "%s";\n' "$line" "$line"
  done < "$TMP.sorted"
} > "$TMP"
if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$TMP" "$OUT"; then echo "$OUT is out of date; run scripts/extract-strings.sh" >&2; exit 1; fi
  echo "$OUT is up to date ($(grep -c '^"' "$OUT") strings)"
  exit 0
fi
mkdir -p "$(dirname "$OUT")"
cp "$TMP" "$OUT"
echo "Wrote $OUT ($(grep -c '^"' "$OUT") strings)"
