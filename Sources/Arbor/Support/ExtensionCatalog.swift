import AppKit
import ArborCore

/// Every extension point, by area (DEC-024), listed by the `extensions` step (scripts/list-extension-points.sh,
/// docs/EXTENSION-POINTS.md). Add new points here; `ExtensionCatalogTests` checks none is missing.
enum ExtensionCatalog {
    static let sections: [(title: String, points: [ExtensionPointInfo])] = [
        ("Interactions in item views", [
            InteractionHooks.openFile, Shortcuts.openTarget, InteractionHooks.commitRename, InteractionHooks.drop, InteractionHooks.dragHover,
            InteractionHooks.leftMouseDown, InteractionHooks.rightMouseDown, InteractionHooks.rightDrag, InteractionHooks.decorateIcon,
            InteractionHooks.itemDetail, ItemHooks.dragWriters, ItemViewHooks.decorateName, ItemViewHooks.underlinesName,
        ]),
        ("Windows, tabs and the search box", [
            WindowHooks.didCreate, WindowHooks.willDisplay, WindowHooks.didDisplay, WindowHooks.selectionChanged,
            WindowHooks.viewStateChanged, WindowHooks.itemFilters, WindowHooks.tabTitle, WindowHooks.openFolder,
            WindowHooks.startLocation, WindowHooks.restoreSession, TabState.visibleItemsFilter,
            BrowserWindowController.networkAddressHandler, BrowserWindowController.unresolvedAddress,
            BrowserWindowController.volumeUnmountHandler,
            AddressBar.recentLocations, AddressBar.editTextProviders, AddressBar.annotationProviders, Breadcrumbs.builders,
            StatusBarView.messageHooks,
            SearchRegistry.factory, SearchRegistry.wrappers, ExplorerSearchController.scopedRequest,
        ]),
        ("Locations, panes and views", [
            LocationRegistry.openHandlers, NavigationPaneHooks.adjustRoots, NavigationPaneHooks.filterChildren,
            NavigationPaneHooks.willReveal, NavigationPaneHooks.decorateCell, NavigationPaneHooks.didExpand,
            NavigationPaneExtras.builders,
            NavigationPaneController.volumeNodes, SidePaneRegistry.wrappers, PreviewPolicy.showsPreviewHandlers,
            PreviewHooks.localURL, DetailsColumns.providers, FileSorter.columnValues, ViewOptions.folderKindResolver,
            ViewOptions.columnsEdited, FolderViews.virtualFolders, IconProvider.itemIconOverrides, IconProvider.locationIconOverrides,
            ItemBadges.providers, TileView.showsDescriptions, GalleryGridView.showsDescriptions,
            VolumeCatalog.adjustments, VolumeCatalog.iconOverride, VolumeCatalog.statusOverride, PropertiesTabs.extraTabs,
        ]),
        ("Commands and menus", [
            CommandDispatcher.menuTitleHook, CommandDispatcher.menuBuilt, ContextMenuKey.presenter,
        ]),
        ("File operations and the Trash", [
            OperationCenter.prepareJob, OperationCenter.admission, OperationCenter.afterRun, OperationCenter.jobFinished,
            OperationCenter.jobCancelled, TransferPreflight.checks, SystemTrash.observers,
        ]),
        ("Settings and scripted checks", [
            FolderOptionsHistory.clearers, FolderOptionsWindowController.generalGroups, PerformanceDebug.extraMemoryFields,
            DebugScript.loggers,
        ]),
    ]

    static var points: [ExtensionPointInfo] { sections.flatMap(\.points) }

    /// One line per point (kind, name, contributions in run order), then overrides, script steps and feature
    /// order. No paths or machine details: safe to publish.
    static func listing() -> String {
        var lines = ["features (registration order): " + Features.registeredOrder.joined(separator: ", ")]
        lines += points.map(\.listing)
        lines += CommandRegistry.shared.extensionPoints.map(\.listing)
        lines.append("script steps: " + DebugScript.stepNames.map { "\($0.name) [\($0.feature)]" }.joined(separator: ", "))
        let errors = ExtensionRegistry.shared.errors
        lines.append("errors: " + (errors.isEmpty ? "none" : errors.map(\.description).joined(separator: " | ")))
        return lines.joined(separator: "\n") + "\n"
    }

    /// docs/EXTENSION-POINTS.md (`scripts/list-extension-points.sh --markdown docs/EXTENSION-POINTS.md`).
    static func markdown() -> String {
        func row(_ point: ExtensionPointInfo) -> String {
            let who = point.contributions.isEmpty ? "—" : point.contributions.map { contribution in
                "`\(contribution.id)`" + (contribution.order == .normal ? "" : " (\(contribution.order))")
            }.joined(separator: ", ")
            let signature = point.signature.isEmpty ? "" : " `\(point.signature)`"
            return "| `\(point.name)` | \(point.kind.rawValue) | \(point.purpose)\(signature) | \(who) |"
        }
        let header = ["| Point | Kind | For | Contributions, in run order |", "|---|---|---|---|"]
        var lines = [
            "# Extension points",
            "",
            "Generated by `scripts/list-extension-points.sh --markdown docs/EXTENSION-POINTS.md` from a headless run of the app;",
            "don't edit by hand. How to use them: docs/ARCHITECTURE.md \"Writing a feature\" (DEC-024).",
            "",
            "Kinds: **Handlers** ask contributions in run order and take the first answer; **Observers** call every",
            "contribution; a **Pipeline** passes a value through every contribution; **Provided** has one provider and a",
            "default. Run order is `ExtensionOrder` (first, early, normal, late, last), then registration order.",
            "",
            "## Features",
            "",
            "Registered in this order (each after what it requires; \"core\" is required by all).",
            "",
            "| Feature | Requires |",
            "|---|---|",
        ]
        let byID = Dictionary(Features.all.map { ($0.id, $0) }, uniquingKeysWith: { a, _ in a })
        for id in Features.registeredOrder {
            let requires = byID[id]?.requires ?? []
            lines.append("| `\(id)` | \(requires.isEmpty ? "—" : requires.map { "`\($0)`" }.joined(separator: ", ")) |")
        }
        for section in sections {
            lines += ["", "## \(section.title)", ""] + header + section.points.map(row)
        }
        lines += ["", "## Per-command overrides", "",
                  "Only commands that other features change are listed (`CommandRegistry.override`, `hide`, `hide(prefix:)`,",
                  "`adjustSubmenu`, `beforePerform`, `replace`).", ""] + header
        lines += CommandRegistry.shared.extensionPoints.map(row)
        return lines.joined(separator: "\n") + "\n"
    }

    /// extensions:/path appends `listing()`; extensions:md:/path writes `markdown()`.
    static func registerScriptStep() {
        DebugScript.registerStep("extensions") { argument, _ in
            let asMarkdown = argument.hasPrefix("md:")
            let path = asMarkdown ? String(argument.dropFirst(3)) : argument
            let text = asMarkdown ? markdown() : listing()
            if asMarkdown {
                try? text.write(toFile: path, atomically: true, encoding: .utf8)
            } else if let handle = FileHandle(forWritingAtPath: path) {
                handle.seekToEndOfFile()
                handle.write(Data(text.utf8))
                handle.closeFile()
            } else {
                try? text.write(toFile: path, atomically: true, encoding: .utf8)
            }
            return 0.1
        }
    }
}
